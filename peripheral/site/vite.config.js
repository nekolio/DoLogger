import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// base: './' — the site is served from a subpath
// (https://nekolio.github.io/DoLogger/), so every asset URL must be
// relative to the page, not absolute.
//
// All SVG assets (icons.svg, favicon, …) live in public/ and are
// referenced as runtime URLs ("./assets/…"). The SFC compiler would
// otherwise rewrite static href/src (including <use href>) into module
// imports that vite resolves against src/assets/*. Disabling needs an
// empty-tags object, not `false`: plugin-vue v6 converts `false` back
// into the default tag list, while an explicit `tags` object replaces
// the defaults entirely (every list empty → no rewrite).
const noAssetTransform = { video: [], source: [], img: [], image: [], use: [] }

// hero.svg single-source rule: docs/assets/hero.svg is the ONLY copy in
// the repository (regenerated by peripheral/tools/hero-svg/hero_generator.py).
// The site never keeps its own copy — dev serves the repo file and the
// build emits it into dist at its runtime URL, so every reference in the
// source ("./assets/hero.svg") stays a plain relative path. The CI build
// script re-copies the docs file into dist as belt-and-braces anyway
// (peripheral/github/scripts/build-site.sh).
const HERO_URL = '/assets/hero.svg'
const HERO_SRC = fileURLToPath(new URL('../../docs/assets/hero.svg', import.meta.url))

function heroSingleSource() {
  return {
    name: 'dologger-hero-single-source',
    configureServer(server) {
      server.middlewares.use(HERO_URL, (_req, res) => {
        res.setHeader('Content-Type', 'image/svg+xml')
        res.end(readFileSync(HERO_SRC))
      })
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'assets/hero.svg', source: readFileSync(HERO_SRC) })
    }
  }
}

export default defineConfig({
  base: './',
  plugins: [heroSingleSource(), vue({ template: { transformAssetUrls: noAssetTransform } })],
  build: { outDir: 'dist' }
})
